"""Incident records for the live simulation feed.

Every incident in RESQIVO is simulated: generated by the simulator, or created
by an operator from a simulated call. Nothing here comes from, or is sent to,
real emergency services.
"""

from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, StringConstraints

from app.models.scenario import DisasterSeverity, DisasterType

SIMULATION_NOTICE = (
    "Simulated incidents for planning and education only. RESQIVO does not "
    "receive real emergency calls and does not dispatch, book or contact anyone."
)

IncidentStatus = Literal["new", "acknowledged", "closed"]
IncidentSource = Literal["simulation", "call", "manual"]
# "simulated": coordinates generated by the simulator; "operator_entered": typed
# by an operator; "unconfirmed": no coordinates, location is text only.
LocationConfidence = Literal["simulated", "operator_entered", "unconfirmed"]

INCIDENT_ID_PATTERN = r"^INC-[0-9a-f]{8}$"
MAX_INCIDENTS = 500
MAX_LIST_ITEMS = 10

ShortText = Annotated[
    str, StringConstraints(strip_whitespace=True, min_length=1, max_length=100)
]


class Coordinates(BaseModel):
    model_config = ConfigDict(extra="forbid")

    lat: float = Field(ge=-90, le=90)
    lon: float = Field(ge=-180, le=180)


class IncidentFields(BaseModel):
    """The editable facts of an incident."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    title: str = Field(min_length=1, max_length=120)
    disaster_type: DisasterType
    severity: DisasterSeverity
    summary: str = Field(default="", max_length=2000)
    location: str = Field(min_length=1, max_length=200)
    coordinates: Coordinates | None = None
    affected_people: int | None = Field(default=None, ge=0, le=10_000_000)
    needs: list[ShortText] = Field(default_factory=list, max_length=MAX_LIST_ITEMS)
    missing_fields: list[ShortText] = Field(
        default_factory=list, max_length=MAX_LIST_ITEMS
    )


class IncidentCreate(IncidentFields):
    """An incident created by an operator, by hand or from a simulated call.
    Simulator incidents are created only through POST /incidents/simulate."""

    source: Literal["call", "manual"] = "manual"


class Incident(IncidentFields):
    incident_id: str = Field(pattern=INCIDENT_ID_PATTERN)
    status: IncidentStatus = "new"
    source: IncidentSource
    location_confidence: LocationConfidence
    synthetic: Literal[True] = True
    created_at: datetime
    updated_at: datetime


class IncidentList(BaseModel):
    incidents: list[Incident]
    # Increases whenever the store changes; the stream sends it as a signal.
    version: int
    notice: str = SIMULATION_NOTICE


class StatusUpdate(BaseModel):
    """An operator's status change. RESQIVO never changes status by itself."""

    model_config = ConfigDict(extra="forbid")

    status: IncidentStatus


class SimulationRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    scenario: Literal["flood", "cyclone"]
    count: int = Field(default=8, ge=1, le=20)
    reset_existing: bool = False
    # Fixes the generated incidents, for repeatable demonstrations and tests.
    seed: int | None = Field(default=None, ge=0)


class DeleteResult(BaseModel):
    deleted: int
